#!/usr/bin/env node
// ADR 0006, decision 7: which parts of the dictionary each area of the app
// sends to the browser, worked out from the code itself.
//
// A component reads the dictionary in the browser only through the
// `useTranslations` hook. For each area (a folder under
// app/(product)/app/(authenticated)) this follows the
// imports from the area's own files, through every component and module
// they reach, and collects the namespaces those files pass to the hook. The
// shell (the layouts above the areas, the sign-in screens, the error pages)
// is "global": every page gets it. An area gets only what its own screens
// read beyond that.
//
//   node scripts/i18n/route-messages.mjs           writes the generated file
//   node scripts/i18n/route-messages.mjs --check   fails if it is stale
//
// tests/unit/i18n-route-messages.test.ts runs the check, so a change that
// moves a component between areas, or adds a namespace, cannot ship with a
// stale list: the screen would show keys instead of words, in the browser
// only, where no server test would see it.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const PRODUCT = "app/(product)";
const AUTHED = `${PRODUCT}/app/(authenticated)`;
export const GENERATED = "lib/i18n/route-messages.generated.ts";

const SPEC = /(?:import|export)\s[^"'`;]*?from\s*["']([^"']+)["']|import\(\s*["']([^"']+)["']\s*\)|import\s*["']([^"']+)["']/g;
const HOOK = /useTranslations\(\s*["']([^"']+)["']\s*\)/g;

function resolve(fromFile, spec) {
  let base;
  if (spec.startsWith("@/")) base = path.join(ROOT, spec.slice(2));
  else if (spec.startsWith(".")) base = path.resolve(path.dirname(fromFile), spec);
  else return null;
  for (const c of [base, `${base}.tsx`, `${base}.ts`, path.join(base, "index.tsx"), path.join(base, "index.ts")]) {
    if (fs.existsSync(c) && fs.statSync(c).isFile() && /\.tsx?$/.test(c)) return c;
  }
  return null;
}

const cache = new Map();
function scan(file) {
  if (cache.has(file)) return cache.get(file);
  const src = fs.readFileSync(file, "utf8");
  const deps = [...src.matchAll(SPEC)].map((m) => resolve(file, m[1] ?? m[2] ?? m[3])).filter(Boolean);
  const namespaces = [...src.matchAll(HOOK)].map((m) => m[1]);
  const out = { deps, namespaces };
  cache.set(file, out);
  return out;
}

function reach(entries) {
  const seen = new Set();
  const stack = [...entries];
  const namespaces = new Set();
  while (stack.length) {
    const f = stack.pop();
    if (seen.has(f)) continue;
    seen.add(f);
    const { deps, namespaces: ns } = scan(f);
    ns.forEach((n) => namespaces.add(n));
    stack.push(...deps);
  }
  return namespaces;
}

function filesIn(dir) {
  const out = [];
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return out;
  for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
    const p = path.join(abs, e.name);
    if (e.isDirectory()) out.push(...filesIn(path.relative(ROOT, p)));
    else if (/\.tsx?$/.test(e.name) && !e.name.endsWith(".d.ts")) out.push(p);
  }
  return out;
}

/// The smallest list of paths that covers every namespace: "a.b" is dropped
/// when "a" is there.
function minimal(set) {
  const all = [...set].sort();
  return all.filter((p) => !all.some((q) => q !== p && p.startsWith(`${q}.`)));
}

export function computeRouteMessages() {
  cache.clear();
  // Global: everything above the areas and every screen outside them.
  const authedRoot = fs.readdirSync(path.join(ROOT, AUTHED), { withFileTypes: true });
  const globalEntries = [
    ...filesIn(PRODUCT).filter((f) => !f.startsWith(path.join(ROOT, AUTHED) + path.sep)),
    // The home page sits beside the areas' layout, not inside a folder of
    // its own, so it counts as the shell; its browser parts are small.
    ...authedRoot.filter((e) => e.isFile() && /\.tsx?$/.test(e.name)).map((e) => path.join(ROOT, AUTHED, e.name)),
  ];
  const global = minimal(reach(globalEntries));
  const covered = (ns) => global.some((g) => ns === g || ns.startsWith(`${g}.`));

  const areas = {};
  const add = (area, entries) => {
    const ns = minimal(new Set([...reach(entries)].filter((n) => !covered(n))));
    if (ns.length) areas[area] = ns;
  };
  for (const e of authedRoot.filter((d) => d.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    add(e.name, filesIn(`${AUTHED}/${e.name}`));
  }
  return { global, areas };
}

export function renderGenerated({ global, areas }) {
  const list = (xs, pad) => xs.map((x) => `${pad}"${x}",\n`).join("");
  return `// Generated by scripts/i18n/route-messages.mjs. Do not edit by hand:
// run \`node scripts/i18n/route-messages.mjs\` after changing which
// components an area uses or which namespaces they read.
//
// ADR 0006, decision 7: the dictionary parts the browser gets. Every page
// gets GLOBAL_MESSAGE_PATHS; a page in an area also gets that area's list
// (components/app/ScopedMessages.tsx).

export const GLOBAL_MESSAGE_PATHS = [
${list(global, "  ")}] as const;

export const AREA_MESSAGE_PATHS = {
${Object.entries(areas)
  .map(([a, xs]) => `  ${JSON.stringify(a)}: [\n${list(xs, "    ")}  ],\n`)
  .join("")}} as const satisfies Record<string, readonly string[]>;

export type MessageArea = keyof typeof AREA_MESSAGE_PATHS;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = renderGenerated(computeRouteMessages());
  const file = path.join(ROOT, GENERATED);
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (current !== text) {
      console.error(`${GENERATED} is stale: run node scripts/i18n/route-messages.mjs`);
      process.exit(1);
    }
    console.log("up to date");
  } else {
    fs.writeFileSync(file, text);
    console.log(`wrote ${GENERATED}`);
  }
}
